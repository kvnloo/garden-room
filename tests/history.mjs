// Deterministic touch UI tests + real read-only API smoke. No owner state writes.
import { chromium } from 'playwright-core';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const base = process.argv[2] || 'http://127.0.0.1:8790';
const key = fs.readFileSync(new URL('../data/.token', import.meta.url), 'utf8').trim();
const out = new URL('../work/history-shots/', import.meta.url).pathname; fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const ctx = await browser.newContext({ viewport: { width: 412, height: 915 }, deviceScaleFactor: 1.5, isMobile: true, hasTouch: true });
const page = await ctx.newPage(), errors = [];
page.on('pageerror', (err) => errors.push(String(err)));
const result = {};
const ok = (name, value) => { assert.ok(value, name); result[name] = 'PASS'; };
await page.route('**/api/state', (r) => r.request().method() === 'GET' ? r.fulfill({ json: {} }) : r.fulfill({ json: { ok: true } }));
await page.route('**/api/layouts', (r) => r.fulfill({ json: [] }));
let photos = [0,1,2].map((i) => ({ id: `${i}`.padStart(12, '0'), ts: ['2026-04-01T12:00:00-05:00','2026-07-01T12:00:00-05:00','2026-10-18T12:00:00-05:00'][i], thumb512: `/plants/p0${i+1}.webp`, thumb1600: `/plants/p0${i+1}.webp`, assignment: { id: 'p01', score: .95, box: [.1,.1,.8,.9] } }));
const library = [...photos, { ...photos[0], id: '000000000003' }];
await page.route('**/api/history/**', (r) => {
  const url = r.request().url();
  if (url.includes('/assign')) { const b = r.request().postDataJSON(); photos = photos.filter((p) => p.id !== b.photo); if (b.on) photos.push(library.find((p) => p.id === b.photo)); return r.fulfill({ json: { ok: true } }); }
  if (url.includes('/photos?')) return r.fulfill({ json: { photos: library, total: library.length, hasMore: false } });
  return r.fulfill({ json: { photos: [...photos].sort((a,b) => a.ts.localeCompare(b.ts)), saplingFraction: .15 } });
});
await page.goto(`${base}/#k=${key}`);
await page.waitForFunction(() => window.GR && window.__garden && document.querySelector('#score').textContent !== '–');
await page.evaluate(() => GR.renderer.setPixelRatio(.65));
await page.waitForTimeout(600);
const open = async () => {
  await page.evaluate(() => GR.select('p01'));
  await page.getByRole('button', { name: 'History', exact: true }).click();
  await page.waitForSelector('#plant-history');
};
await open();
ok('History action + timeline + photo grid', await page.locator('[data-photo]').count() === 3);
ok('no horizontal overflow at phone width', await page.evaluate(() => document.querySelector('#plant-history').scrollWidth <= document.querySelector('#plant-history').clientWidth + 1));
await page.screenshot({ path: out + '01-history.png' });
await page.locator('[data-scrub]').evaluate((el) => { el.value = '0'; el.dispatchEvent(new Event('input')); });
ok('sapling is 15%, pot stays full-size', await page.evaluate(() => Math.abs(GR.meshOf('p01').userData.holder.userData.historyGrowth.scale.y - .15) < .001 && GR.meshOf('p01').scale.y === 1));
await page.locator('[data-play]').click();
await page.waitForFunction(() => +document.querySelector('[data-scrub]').value > 0);
const mid = await page.locator('[data-scrub]').inputValue();
ok('play advances real-date scrubber', +mid > 0 && +mid < 1);
await page.locator('[data-play]').click(); const paused = await page.locator('[data-scrub]').inputValue(); await page.waitForTimeout(150);
ok('pause freezes timeline', paused === await page.locator('[data-scrub]').inputValue());
await page.locator('#history-speed').evaluate((el) => { el.value = '4'; el.dispatchEvent(new Event('input')); });
ok('speed control 4x', await page.locator('[data-speed-label]').textContent() === '4×');
await page.locator('[data-real]').check();
ok('real timelapse restores model dimensions', await page.evaluate(() => (!GR.meshOf('p01').userData.holder.userData.historyGrowth || GR.meshOf('p01').userData.holder.userData.historyGrowth.scale.y === 1)));
await page.locator('[data-play]').click(); await page.waitForFunction(() => +document.querySelector('[data-scrub]').value === 1, null, { timeout: 6000 });
ok('4x playback finishes', await page.locator('[data-scrub]').inputValue() === '1');
await page.screenshot({ path: out + '02-real.png' });
await page.locator('[data-photo]').first().click();
await page.waitForSelector('dialog[open]');
ok('full viewer opens', await page.locator('dialog img').getAttribute('src') !== null);
const before = await page.locator('[data-counter]').textContent();
await page.locator('dialog [data-next]').click();
ok('viewer next', before !== await page.locator('[data-counter]').textContent());
// Physical touch swipe via CDP.
const box = await page.locator('.history-view-image').boundingBox(), cdp = await ctx.newCDPSession(page);
const counter = await page.locator('[data-counter]').textContent();
await cdp.send('Input.dispatchTouchEvent', { type:'touchStart', touchPoints:[{ x:box.x+box.width*.8, y:box.y+box.height*.5 }] });
await cdp.send('Input.dispatchTouchEvent', { type:'touchMove', touchPoints:[{ x:box.x+box.width*.2, y:box.y+box.height*.5 }] });
await cdp.send('Input.dispatchTouchEvent', { type:'touchEnd', touchPoints:[] });
ok('viewer touch swipe', counter !== await page.locator('[data-counter]').textContent());
await page.screenshot({ path: out + '03-viewer.png' });
await page.locator('[data-correct]').click(); await page.waitForTimeout(200);
ok('not-this-plant updates read-back grid', await page.locator('[data-photo]').count() === 2);
await page.locator('[data-add]').click(); await page.waitForSelector('[data-library-photo]');
await page.locator('[data-library-photo]').last().click(); await page.locator('[data-correct]').click(); await page.waitForTimeout(200);
ok('add-to-plant correction', photos.some((p) => p.id === '000000000003'));
await page.locator('[data-scrub]').evaluate((el) => { el.value = '.2'; el.dispatchEvent(new Event('input')); });
await page.locator('[data-real]').uncheck();
await page.evaluate(() => GR.closeSheet()); await page.waitForTimeout(150);
ok('closing restores model and removes overlay', await page.evaluate(() => (!GR.meshOf('p01').userData.holder.userData.historyGrowth || GR.meshOf('p01').userData.holder.userData.historyGrowth.scale.y === 1) && !document.querySelector('.history-float')));
await open();
await page.evaluate(() => GR.openItem('p02')); await page.waitForTimeout(150);
ok('switching sheet cleans up animation', await page.locator('.history-float').count() === 0);
await open(); await page.locator('[data-done]').click();
ok('no JS errors', !errors.length);
// Real server read-only smoke, separate from deterministic test fixtures.
const response = await ctx.request.get(base + '/api/history/plant/p01', { headers: { 'X-Garden-Key': key } });
ok('real history API responds', response.ok());
const actual = await response.json();
ok('real API does not disclose private source paths', !JSON.stringify(actual).includes('$PRIVATE_DATA'));
console.log(JSON.stringify(result, null, 2));
await browser.close();
